
import os
import psycopg
from psycopg.rows import dict_row
from dotenv import load_dotenv

# Load environment variables
BASE_DIR = os.path.dirname(os.path.abspath(__file__))

load_dotenv(os.path.join(BASE_DIR, "..", ".env"))
load_dotenv(os.path.join(BASE_DIR, ".env"))

# Neon PostgreSQL connection URL
DATABASE_URL = os.getenv("DATABASE_URL")


# Connect to Neon PostgreSQL
def get_db_connection():

    if not DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL is missing. Check your .env file."
        )

    conn = psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row
    )

    return conn


# Create plants table
def create_tables():

    conn = get_db_connection()

    try:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS plants (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                plant_name TEXT,
                image_filename TEXT NOT NULL,
                health_status TEXT,
                disease TEXT,
                watering_advice TEXT,
                symptoms TEXT,
                treatment TEXT,
                severity TEXT,
                symptom_explanation TEXT,
                prevention TEXT,
                recovery_advice TEXT,
                scan_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)

        conn.commit()

    finally:
        conn.close()


# Migrate existing database columns
def migrate_database():

    conn = get_db_connection()

    try:
        new_columns = [
            ("symptoms", "TEXT"),
            ("treatment", "TEXT"),
            ("severity", "TEXT"),
            ("symptom_explanation", "TEXT"),
            ("prevention", "TEXT"),
            ("recovery_advice", "TEXT")
        ]

        for column_name, column_type in new_columns:
            conn.execute(f"""
                ALTER TABLE plants
                ADD COLUMN IF NOT EXISTS {column_name} {column_type}
            """)

        conn.commit()

    finally:
        conn.close()


# Initialize database
def init_db():

    create_tables()
    migrate_database()

    print(
        "PlantPulse Neon PostgreSQL database initialized successfully!"
    )

